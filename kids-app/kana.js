// カタカナ 1字 → おなじ 音 の ひらがな（今は ア行・カ行の 10字）
const KATAKANA_TO_HIRAGANA = {
  "ア": "あ", "イ": "い", "ウ": "う", "エ": "え", "オ": "お",
  "カ": "か", "キ": "き", "ク": "く", "ケ": "け", "コ": "こ",
};

// 1もじ を よむ とき に つかう。カタカナ なら おなじ 音 の ひらがな に なおす
function kanaVoiceChar(c) { return KATAKANA_TO_HIRAGANA[c] || c; }
