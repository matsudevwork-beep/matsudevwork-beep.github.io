/* =========================================================
   せんかき（運筆）の問題データ
   ---------------------------------------------------------
   ・path は SVG の線の書き方です（M=始点へ移動、L=直線、
     H=横線、V=縦線、C/S/Q=曲線、A=円弧）。
   ・画面は 横360 × 縦480 のマス目で考えています。
   ・問題を増やすときは、LEVELS の配列に1行足すだけです。
     下の「形をつくる道具」を使うと、数字を変えるだけで形を作れます。
   ・やさしい → むずかしい の順にならべています（全61問）。
   ========================================================= */

/* --- 形をつくる道具 --- */
const r1 = (n) => Math.round(n);

// 点を順番に まっすぐ つなぐ： poly([x, y], [x, y], ...)
const poly = (...pts) => "M" + pts.map(([x, y]) => `${r1(x)} ${r1(y)}`).join(" L");

// ぎざぎざ（やま が n こ）
function zigzag(n, x1, x2, yBase, yTop) {
  const w = (x2 - x1) / (2 * n), pts = [[x1, yBase]];
  for (let i = 0; i < n; i++) pts.push([x1 + w * (2 * i + 1), yTop], [x1 + w * (2 * i + 2), yBase]);
  return poly(...pts);
}

// たての ぎざぎざ
function zigzagV(n, y1, y2, xBase, xTop) {
  const h = (y2 - y1) / (2 * n), pts = [[xBase, y1]];
  for (let i = 0; i < n; i++) pts.push([xTop, y1 + h * (2 * i + 1)], [xBase, y1 + h * (2 * i + 2)]);
  return poly(...pts);
}

// なみなみ（やま と たに で 1つ。n こ ならべる。amp＝なみの高さ）
function wave(n, x1, x2, y, amp) {
  const w = (x2 - x1) / (2 * n), k = amp * 1.33;
  let d = `M${r1(x1)} ${y}`;
  for (let i = 0; i < 2 * n; i++) {
    const a = x1 + w * i, b = a + w, dy = i % 2 === 0 ? -k : k;
    d += ` C${r1(a + w / 3)} ${r1(y + dy)} ${r1(b - w / 3)} ${r1(y + dy)} ${r1(b)} ${y}`;
  }
  return d;
}

// たての なみなみ
function waveV(n, y1, y2, x, amp) {
  const h = (y2 - y1) / (2 * n), k = amp * 1.33;
  let d = `M${x} ${r1(y1)}`;
  for (let i = 0; i < 2 * n; i++) {
    const a = y1 + h * i, b = a + h, dx = i % 2 === 0 ? k : -k;
    d += ` C${r1(x + dx)} ${r1(a + h / 3)} ${r1(x + dx)} ${r1(b - h / 3)} ${x} ${r1(b)}`;
  }
  return d;
}

// かいだん（だん が n こ）
function stairs(n, x1, y1, x2, y2) {
  const w = (x2 - x1) / n, h = (y2 - y1) / n, pts = [[x1, y1]];
  for (let i = 0; i < n; i++) pts.push([x1 + w * (i + 1), y1 + h * i], [x1 + w * (i + 1), y1 + h * (i + 1)]);
  return poly(...pts);
}

// まる・だえん（すこし すきまを あけて、●と★が かさならないように）
// dir＝1 で 右まわり、-1 で 左まわり
function circle(cx, cy, rx, ry = rx, gapDeg = 40, dir = 1) {
  const pts = [];
  for (let a = 0; a <= 360 - gapDeg; a += 6) {
    const t = (-90 + dir * a) * Math.PI / 180;
    pts.push([cx + rx * Math.cos(t), cy + ry * Math.sin(t)]);
  }
  return poly(...pts);
}

// うずまき（inward＝true で 外から まんなかへ）
function spiral(cx, cy, rMax, turns, inward = false) {
  const pts = [], steps = Math.round(turns * 60);
  for (let i = 0; i <= steps; i++) {
    const f = i / steps, r = 14 + (rMax - 14) * (inward ? 1 - f : f);
    const t = -Math.PI / 2 + f * turns * 2 * Math.PI;
    pts.push([cx + r * Math.cos(t), cy + r * Math.sin(t)]);
  }
  return poly(...pts);
}

// くるくる：よこに すすみながら、わっか を かく
// centers＝わっかの 場所（x）、r＝わっかの 大きさ
function loops(y, r, centers, x1, x2) {
  let d = `M${x1} ${y}`;
  centers.forEach((cx) => {
    d += ` H${cx} a${r} ${r} 0 0 0 0 ${-2 * r} a${r} ${r} 0 0 0 0 ${2 * r}`;
  });
  return d + ` H${x2}`;
}

